// The sync server's emails and notifications in the reader's language. The Worker (cloud/) can't load the app's catalogs, so
// this copies the translations of its own strings, the ones src/i18n/mailStrings.ts lists, out of src/i18n/catalogs/*.json
// into cloud/src/mailCatalog.ts. Run it after changing either:
//
//   node scripts/i18n/mail-catalog.mjs           writes cloud/src/mailCatalog.ts
//   node scripts/i18n/mail-catalog.mjs --check   writes nothing, and fails when that file is out of date
//
// The file is keyed [locale][English] like the catalogs. A count is keyed by its singular English, as the Worker looks it up,
// and by its plural too, as the app's catalogs key it, so either finds it; its value is the catalog's plural forms.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stringsIn } from './extract.mjs';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const SOURCE = join(ROOT, 'src/i18n/mailStrings.ts');
const CATALOGS = join(ROOT, 'src/i18n/catalogs');
export const OUT = join(ROOT, 'cloud/src/mailCatalog.ts');

/** The mail strings, in the order mailStrings.ts lists them: { text, one } (one: a count's singular; text is its plural). */
export function mailStrings() {
  return stringsIn(readFileSync(SOURCE, 'utf8'));
}

/** Each locale's translations of the mail strings, from its catalog: { [locale]: { [english]: string | plural forms } }. */
export function mailCatalog() {
  const strings = mailStrings();
  const out = {};
  for (const file of readdirSync(CATALOGS).filter((f) => f.endsWith('.json')).sort()) {
    const catalog = JSON.parse(readFileSync(join(CATALOGS, file), 'utf8'));
    const entries = {};
    for (const { text, one } of strings) {
      const tr = catalog[text];
      if (tr === undefined || tr === '') continue; // not translated yet: the Worker writes the English
      if (one !== undefined) {
        const forms = typeof tr === 'string' ? { other: tr } : tr;
        entries[one] = forms;
        entries[text] = forms;
      } else if (typeof tr === 'string') entries[text] = tr;
    }
    out[file.replace(/\.json$/, '')] = entries;
  }
  return out;
}

/** cloud/src/mailCatalog.ts as it should be. */
export function mailCatalogSource() {
  return [
    '// Generated by scripts/i18n/mail-catalog.mjs from src/i18n/mailStrings.ts and src/i18n/catalogs/*.json. Do not edit it here:',
    '// change the English in mailStrings.ts (and the Worker) or a translation in the catalogs, then run',
    '// node scripts/i18n/mail-catalog.mjs.',
    '//',
    '// The Worker\'s emails and notifications in the reader\'s language: [locale][English] gives the translation, and a count, keyed',
    '// by its singular English (and its plural), gives the forms its language has (Intl.PluralRules categories). English needs no',
    '// entry, and a string missing here is written in English.',
    `export const MAIL_CATALOG: Record<string, Record<string, string | Record<string, string>>> = ${JSON.stringify(mailCatalog(), null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = mailCatalogSource();
  if (process.argv.includes('--check')) {
    let old = '';
    try { old = readFileSync(OUT, 'utf8'); } catch { /* none yet */ }
    if (old !== text) { console.error('cloud/src/mailCatalog.ts is out of date: run node scripts/i18n/mail-catalog.mjs'); process.exit(1); }
    console.log('mailCatalog.ts is up to date');
  } else {
    writeFileSync(OUT, text);
    console.log(`${mailStrings().length} mail strings in cloud/src/mailCatalog.ts`);
  }
}
